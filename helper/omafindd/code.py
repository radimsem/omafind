SOURCE_EXTENSIONS = set(
    "py pyi pyx c h cc cpp cxx hpp hh hxx m mm swift ts tsx mts cts js jsx mjs cjs go rs "
    "java kt kts scala groovy rb php cs fs sh bash zsh fish ps1 lua pl pm r jl dart sql vue "
    "svelte astro html htm css scss sass less gradle cmake mk proto graphql gql tf hcl nix "
    "zig hs ex exs erl clj cljs elm ml mli vim el lisp asm s metal glsl hlsl wgsl cu cuh ino "
    "v sv tex".split()
)
TEXT_EXTENSIONS = set("md markdown rst adoc org txt yaml yml toml".split())
CODE_FILE_NAMES = set(
    "Makefile makefile GNUmakefile Dockerfile Containerfile Justfile justfile Rakefile "
    "Gemfile Podfile Brewfile Procfile Vagrantfile Jenkinsfile".split()
)
SKIPPED_FOLDERS = set(
    "vendor Vendor vendored third_party third-party thirdparty 3rdparty external extern deps "
    "build Build dist out target obj coverage htmlcov generated __generated__ wandb mlruns "
    "lightning_logs".split()
)
CLOSERS = {"end", "fi", "done", "esac", "@end", "#endif", "end;", "end)"}


def configured_roots(settings) -> tuple[Path, ...]:
    return tuple(Path(root).expanduser().absolute()
                 for root in settings().code_roots)


def classify_code(path: Path) -> bool:
    name, ext = path.name, path.suffix[1:].lower()
    if reason(path) or any(part in SKIPPED_FOLDERS for part in path.parts[:-1]):
        return False
    lower = name.lower()
    if lower.endswith((".min.js", ".min.mjs", ".min.css")) or lower.startswith(
        ("license", "licence", "copying", "notice")
    ):
        return False
    return (ext in SOURCE_EXTENSIONS | TEXT_EXTENSIONS | {"ipynb"}
            or name in CODE_FILE_NAMES or name.startswith("Dockerfile"))


def repository_files(root: Path) -> list[Path]:
    result = subprocess.run(["git", "-C", str(root), "ls-files", "--stage", "-z"],
                            capture_output=True, check=True)
    files = set()
    for entry in result.stdout.split(b"\0"):
        if not entry:
            continue
        meta, name = entry.split(b"\t", 1)
        if meta.split()[0] not in (b"100644", b"100755"):
            continue
        path = root / os.fsdecode(name)
        if classify_code(path.relative_to(root)) and path.is_file() and not path.is_symlink():
            files.add(path)
    return sorted(files)


@dataclass(frozen=True)
class Piece:
    text: str
    first: int
    last: int


def check(text: str, *, source: bool = True):
    if "PRIVATE KEY-----" in text:
        raise ValueError("holds a private key")
    if not source:
        return
    for mark in ("DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by",
                 "Generated by the protocol"):
        if mark in text[:1000]:
            raise ValueError("made by a program")
    count = max(1, text.count("\n") + int(bool(text) and not text.endswith("\n")))
    if len(text) // count > 300 and any(len(line) > 3000 for line in text.split("\n")):
        raise ValueError("minified")


def lines(text: str, size: int = 1800) -> list[Piece]:
    rows = text.replace("\r\n", "\n").split("\n")
    if rows[-1] == "":
        rows.pop()
    offsets = [0]
    for row in rows:
        offsets.append(offsets[-1] + len(row) + 1)

    def blank(index):
        return not rows[index].strip()

    def starts_block(index):
        row = rows[index]
        return bool(row and not row[0].isspace() and row[0] not in "})]"
                    and row.strip() not in CLOSERS)

    pieces, start = [], 0
    while start < len(rows):
        while start < len(rows) and blank(start):
            start += 1
        if start == len(rows):
            break
        if len(rows[start]) > size:
            pieces.extend(Piece(rows[start][offset:offset + size], start + 1, start + 1)
                          for offset in range(0, len(rows[start]), size))
            start += 1
            continue
        end = start + 1
        while end < len(rows) and offsets[end + 1] - offsets[start] <= size:
            end += 1
        natural = end >= len(rows)
        if not natural:
            floor = offsets[start] + size * 2 / 5
            cuts = range(end, start + 1, -1)
            for preferred in (True, False):
                cut = next((i for i in cuts if offsets[i] >= floor and (
                    starts_block(i) and blank(i - 1) if preferred
                    else blank(i - 1) or starts_block(i)
                )), None)
                if cut is not None:
                    end, natural = cut, True
                    break
        last = end
        while last > start + 1 and blank(last - 1):
            last -= 1
        pieces.append(Piece("\n".join(rows[start:last]), start + 1, last))
        start = end if natural else max(end - 2, start + 1)
    return pieces


def notebook_cells(data: bytes) -> list[str]:
    notebook = json.loads(data)
    if not isinstance(notebook, dict):
        raise ValueError("not a notebook")
    rows = notebook.get("cells")
    if rows is None:
        worksheets = notebook.get("worksheets", [])
        rows = worksheets[0].get("cells", []) if worksheets else []
    sources = [row.get("source", row.get("input", "")) for row in rows]
    return ["".join(source) if isinstance(source, list) else source for source in sources]


def cells(sources: Sequence[str], size: int = 1800) -> list[Piece]:
    pieces, text, first, last = [], "", 0, 0

    def flush():
        nonlocal text
        if text:
            pieces.append(Piece(text, first, last))
            text = ""

    for number, cell in enumerate(sources, 1):
        body = cell.strip()
        if not body:
            continue
        if len(body) > size:
            flush()
            pieces.extend(Piece(piece.text, number, number) for piece in lines(body, size))
            continue
        if text and len(text) + 2 + len(body) > size:
            flush()
        if not text:
            first, text = number, body
        else:
            text += "\n\n" + body
        last = number
    flush()
    return pieces


def read(path: Path) -> list[Piece]:
    data = path.read_bytes()
    if path.suffix.lower() == ".ipynb":
        sources = notebook_cells(data)
        check("\n".join(sources))
        return cells(sources)
    if b"\0" in data[:8000]:
        raise ValueError("not text")
    # A .ts or .mts file may be an MPEG transport stream, not TypeScript.
    if path.suffix.lower() in (".ts", ".mts") and len(data) >= 400 and (
        all(data[i] == 0x47 for i in (0, 188, 376))
        or all(data[i] == 0x47 for i in (4, 196, 388))
    ):
        raise ValueError("not source code")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        text = data.decode("latin-1")
    check(text, source=path.suffix[1:].lower() in SOURCE_EXTENSIONS)
    return lines(text)


class CodeStore:
    def __init__(self, path: Path):
        from .models import REVISION
        from .store import RUNTIME_TAG, SCHEMA, create_private

        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        create_private(path)
        self.path, self.mount, self.volume, self.label = path, Path("/"), "code", "code"
        self.db = sqlite3.connect(path)
        self.db.row_factory = sqlite3.Row
        self.db.execute("PRAGMA journal_mode=WAL")
        self.db.execute("PRAGMA synchronous=NORMAL")
        self.db.execute("PRAGMA foreign_keys=ON")
        version = self.db.execute("PRAGMA user_version").fetchone()[0]
        if version == 0:
            self.db.executescript(SCHEMA.split("CREATE VIRTUAL TABLE fts", 1)[0] +
                                  "PRAGMA user_version=5;")
        elif version != 5:
            self.close()
            raise ValueError(f"Unsupported index schema: {version}")
        with self.db:
            self.db.executemany("INSERT OR IGNORE INTO meta VALUES(?,?)", [
                ("volume_uuid", "code"), ("volume_label", "code"),
                ("model_rev", REVISION), ("runtime_tag", RUNTIME_TAG),
            ])

    @classmethod
    def open_existing(cls, path: Path, mount: Path):
        from .store import Store

        return Store.open_existing(path, mount)

    def close(self):
        self.db.close()


async def index_code(roots: Sequence[Path], directory: Path, embedder):
    from .embedder import EmbeddingError, document_text
    from .embedding import validated

    roots = tuple(root.expanduser().absolute() for root in roots)
    store = CodeStore(directory / "code.sqlite")
    seen = set()
    try:
        # Text mode caps a request at 512 tokens; an 1800-character code stretch often needs more.
        await embedder.start("full")
        for root in roots:
            for path in repository_files(root):
                relative = path.relative_to(store.mount).as_posix()
                stat = path.stat()
                old = store.db.execute("SELECT * FROM files WHERE path=?", (relative,)).fetchone()
                if old and old["state"] == "done" and (old["size"], old["mtime"]) == (
                    stat.st_size, stat.st_mtime
                ):
                    seen.add(relative)
                    continue
                try:
                    pieces = read(path)
                except (OSError, ValueError, TypeError):
                    continue
                seen.add(relative)
                with store.db:
                    store.db.execute(
                        "INSERT INTO files(path,kind,size,mtime,inode,device) "
                        "VALUES(?, 'code',?,?,?,?) "
                        "ON CONFLICT(path) DO UPDATE SET size=excluded.size,mtime=excluded.mtime,"
                        "inode=excluded.inode,device=excluded.device,state='pending'",
                        (relative, stat.st_size, stat.st_mtime, stat.st_ino, stat.st_dev),
                    )
                    file = store.db.execute(
                        "SELECT id FROM files WHERE path=?", (relative,)
                    ).fetchone()[0]
                    store.db.execute("DELETE FROM segments WHERE file=?", (file,))
                try:
                    vectors = []
                    title = f"{root.name}/{path.relative_to(root).as_posix()}"
                    for offset in range(0, len(pieces), 16):
                        batch = pieces[offset:offset + 16]
                        result = await embedder.embed_documents(
                            [document_text(title, piece.text) for piece in batch]
                        )
                        if len(result) != len(batch):
                            raise ValueError("embedding precision fault")
                        vectors.extend(validated(vector) for vector in result)
                    with store.db:
                        store.db.executemany(
                            "INSERT INTO segments(file,kind,modality,loc,loc_end,excerpt,vec) "
                            "VALUES(?,'code','text',?,?,?,?)",
                            [(file, piece.first, piece.last, piece.text[:400], vector.tobytes())
                             for piece, vector in zip(pieces, vectors, strict=True)],
                        )
                        store.db.execute(
                            "UPDATE files SET state='done',detail=NULL,indexed_at=? WHERE id=?",
                            (time.time(), file),
                        )
                except (EmbeddingError, OSError, ValueError) as error:
                    with store.db:
                        store.db.execute(
                            "UPDATE files SET state='failed',detail=? WHERE id=?",
                            (failures.encode("code-index-failed", str(error)), file),
                        )
        with store.db:
            for row in store.db.execute("SELECT id,path FROM files").fetchall():
                if row["path"] not in seen:
                    store.db.execute("DELETE FROM files WHERE id=?", (row["id"],))
            store.db.execute("INSERT OR REPLACE INTO meta VALUES('code_roots',?)",
                             (json.dumps([str(root) for root in roots]),))
    finally:
        store.close()
